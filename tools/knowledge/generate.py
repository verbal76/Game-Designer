#!/usr/bin/env python3
"""Generate core/.../knowledge/KnowledgeLibraryData.kt from docs/knowledge-library (entries + tags.json + pilot.json).

Only the original-wording fields and source locators (timestamps) are emitted; no transcript text exists in the repository.
Usage: generate.py [--check]   (--check fails if the committed file is out of date)
"""
import json, glob, os, sys, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
LIB = os.path.join(ROOT, "docs/knowledge-library")
OUT = os.path.join(ROOT, "core/src/main/kotlin/com/hotattic/gamedesigner/core/knowledge/KnowledgeLibraryData.kt")
VERSION = 2

def q(s): return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
def qn(s): return "null" if s is None else q(s)
def ql(l): return "listOf(" + ", ".join(q(x) for x in l) + ")"

def tag_matches(tag, word):
    return tag == word or any(w.startswith(word) for w in tag.split("-")) or (len(word) > 4 and word in tag)

def main():
    tags = json.load(open(os.path.join(LIB, "tags.json")))
    pilot = set(json.load(open(os.path.join(LIB, "pilot.json")))["active"])
    sources = json.load(open(os.path.join(LIB, "sources.json")))
    ents = []
    for f in sorted(glob.glob(os.path.join(LIB, "entries/part-*.json"))):
        raw = json.load(open(f)); ents += raw if isinstance(raw, list) else raw["entries"]
    ids = {e["id"] for e in ents}
    assert pilot <= ids, pilot - ids
    lines = ["// GENERATED by tools/knowledge/generate.py from docs/knowledge-library. Do not edit by hand.", "package com.hotattic.gamedesigner.core.knowledge", "",
             "internal object KnowledgeLibraryData {", f"    const val CONTENT_VERSION = {VERSION}", "",
             "    val sources: Map<String, KnowledgeSource> = mapOf("]
    for k, v in sources.items():
        lines.append(f"        {q(k)} to KnowledgeSource({q(k)}, {q(v['title'])}, {q(v['creator'])}, {q(v['kind'])}, {q(v['locator'])}, {q(v['status'])}),")
    lines += ["    )", "",
             "    val concepts: List<KnowledgeConcept> = listOf("]
    for k, v in tags["concepts"].items():
        lines.append(f"        KnowledgeConcept({q(k)}, {ql(v['phrases'])}),")
    lines += ["    )", "", "    val entries: List<KnowledgeEntry> = listOf("]
    for e in ents:
        cs = [k for k, v in tags["concepts"].items() if any(tag_matches(t, w) for t in e["tags"] for w in v["tagWords"])]
        lines.append(f"        KnowledgeEntry({q(e['id'])}, {q(e['game'])}, {q(e.get('start') or e.get('locator'))}, {q(e.get('end') or '')}, {ql(e['tags'])}, {ql(cs)}, {q(e['problem'])}, {q(e['mechanic'])}, {q(e['effect'])}, {qn(e.get('tradeoffs'))}, {qn(e.get('inference'))}, {q(e['question'])}, {ql(e.get('related') or [])}, {q(e['confidence'])}, pilot = {str(e['id'] in pilot).lower()}, sourceId = {q(e.get('source', 'gmtk'))}, classification = {q(e.get('classification', 'SOURCE_SUPPORTED'))}, explicitOnly = {str(bool(e.get('explicitOnly'))).lower()}),")
    lines += ["    )", "}", ""]
    text = "\n".join(lines)
    if "--check" in sys.argv:
        sys.exit(0 if os.path.exists(OUT) and open(OUT).read() == text else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(text)
    print("wrote", OUT, len(ents), "entries,", len(pilot), "pilot")

main()
